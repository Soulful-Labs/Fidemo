// Writes shared/seed/rateCardFiles.ts from rate-card.csv and rate-card-fees.csv at the repository root,
// so the demo's starting rate card is the team's own files, read the same way an upload is.
// Run by build:all and verify:shared; scripts/verify-shared.ts checks the two never drift apart.
import { readFileSync, writeFileSync } from 'node:fs'
const read = (f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n')
const out = `// Generated by scripts/embed-rate-card.mjs from the CSVs at the repository root. Do not edit by hand.
export const RATE_CARD_SEGMENTS_CSV = ${JSON.stringify(read('rate-card.csv'))}
export const RATE_CARD_FEES_CSV = ${JSON.stringify(read('rate-card-fees.csv'))}
export const RATE_CARD_SOURCE = 'Rate card, July 2026 (rate-card.csv, rate-card-fees.csv)'
`
writeFileSync(new URL('../shared/seed/rateCardFiles.ts', import.meta.url), out)
console.log('embedded the rate card')
